test('requirements produce an immutable revision shared by report, graph and exports', async ({ page }) => {
  const errors = watchConsole(page)
  await signIn(page, 'review-e2e@fuze.dev')
  const projects = await (await page.request.get(`${API_URL}/projects`)).json()
  const project = projects.find((item: { name: string }) => item.name === 'Verified reference design')
  await page.goto(`/projects/${project.id}/review`)
  await expect(page.getByRole('heading', { name: project.name })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Validation counts' })).toBeVisible()
  await page.getByRole('region', { name: 'Validation counts' }).evaluate(element => Promise.all(element.getAnimations({ subtree: true }).map(animation => animation.finished)))
  await page.screenshot({ path: 'test-results/revision-report.png', fullPage: true })
  await page.getByRole('button', { name: 'Requirements', exact: true }).click()
  await page.getByRole('spinbutton', { name: 'input voltage', exact: true }).fill('5')
  await page.getByRole('button', { name: 'Save and revalidate', exact: true }).click()
  await expect(page).toHaveURL(`/design/${project.id}`)
  await expect(page.getByTestId('revision-notice')).toContainText('Revision saved and revalidated')
  await expect(page.getByRole('button', { name: /Resolve Conflicts/ })).toBeEnabled()
  await page.getByRole('link', { name: 'Review design', exact: true }).click()
  await expect(page.getByLabel('Viewing revision')).toContainText('Requirements updated and revalidated')
  await page.getByRole('button', { name: 'Review', exact: true }).click()
  await expect(page.locator('article').filter({ hasText: 'voltage overlap' })).toContainText('FAIL')
  const reportHref = await page.getByRole('link', { name: 'Export report' }).getAttribute('href')
  const report = await (await page.request.get(reportHref!)).json()
  const csvHref = await page.getByRole('link', { name: 'Export BOM' }).getAttribute('href')
  expect(await (await page.request.get(csvHref!)).text()).toContain(report.revision_id)
  await page.getByRole('button', { name: 'Revision history' }).click()
  await page.getByLabel('Compare against').selectOption({ index: 1 })
  await expect(page.getByText('input voltage: 3.3 → 5')).toBeVisible()
  await page.getByRole('link', { name: 'Back to workspace' }).click()
  await expect(page.getByTestId('workspace-project-name')).toHaveText(project.name)
  await expect(page.getByRole('button', { name: /Resolve Conflicts/ })).not.toBeDisabled()
  await expect(page.locator('body')).not.toContainText('undefined resolved')
  await page.screenshot({ path: 'test-results/revision-workspace.png', fullPage: true })
  expect(errors).toEqual([])
})

